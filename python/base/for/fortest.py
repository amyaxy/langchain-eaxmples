# for 循环遍历列表
numbers = [1, 2, 3, 4, 5]

for num in numbers:
    print(num)
# 输出:
# 1
# 2
# 3
# 4
# 5

# 使用 range() 生成数字序列
for i in range(5):
    print(i)
# 输出:
# 0
# 1
# 2
# 3
# 4

# 指定起始和结束点
for i in range(2, 7):
    print(i)
# 输出:
# 2
# 3
# 4
# 5
# 6

# 指定步长
for i in range(1, 10, 2):
    print(i)
# 输出:
# 1
# 3
# 5
# 7
# 9
