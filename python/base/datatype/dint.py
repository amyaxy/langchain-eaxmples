# 整数
a = 10
b = -5
c = 0
print(a, type(a))  # 输出: 10 <class 'int'>
print(b, type(b))  # 输出: -5 <class 'int'>
print(c, type(c))  # 输出: 0 <class 'int'>


# 加法
print(a + b)  # 输出: 5

# 减法
print(a - b)  # 输出: 15

# 乘法
print(a * b)  # 输出: -50

# 除法
print(a / 2)  # 输出: 5.0

# 整除
print(a // 3)  # 输出: 3

# 取余
print(a % 3)  # 输出: 1

# 幂运算
print(a**2)  # 输出: 100
